const knownWords = new Set(COMMON_WORDS.map((w) => w.toLowerCase()))

/** True if the word is valid English or a construction term — never auto-correct. */
export function isKnownWord(word: string): boolean {
  const lower = word.toLowerCase()
  if (knownWords.has(lower)) return true
  if (isConstructionTerm(word)) return true
  return false
}

/**
 * Local-only spelling fix. Returns corrected word or null.
 * Never calls AI — uses typo map + construction/common dictionaries.
 */
export function correctFromDictionary(word: string): string | null {
  if (isKnownWord(word)) return null

  const lower = word.toLowerCase()
  const fix = COMMON_TYPOS[lower]
  if (!fix) return null

  // Never "correct" into something that isn't intended if fix is also unknown — typo map is trusted
  if (word[0] === word[0]!.toUpperCase() && word.slice(1) === word.slice(1).toLowerCase()) {
    return fix.charAt(0).toUpperCase() + fix.slice(1)
  }
  if (word === word.toUpperCase() && !fix.includes(' ')) {
    return fix.toUpperCase()
  }
  return fix
}
